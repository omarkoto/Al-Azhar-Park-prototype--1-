function getInitialLang(): 'en' | 'ar' {
  if (typeof window === 'undefined') return 'en'
  return window.localStorage.getItem(STORAGE_KEY) === 'ar' ? 'ar' : 'en'
}

void i18n.use(initReactI18next).init({
  resources,
  lng: getInitialLang(),
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
})

export default i18n
